print(4 + 5) # Addition: adds two numbers

print(10 - 3) # Subtraction: subtracts the second number from the first

print(5 * 4) # Multiplication: multiplies two numbers

print(15 / 2) # Division: divides and gives a float result

print(15 // 2) # Floor Division: divides and rounds down to the nearest whole number

print(15 % 2) # Modulus: gives the remainder

print(2 ** 3) # Exponentiation: first number raised to the power of the second number

