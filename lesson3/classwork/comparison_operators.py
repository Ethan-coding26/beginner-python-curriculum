# Comparison Operators compare values and return a boolean result True or False
print(5 < 3) # greater than
print(5 > 3) # less than
print(5 >= 5) # greater than or equal to
print(4 <= 5) # less than or equal to
print(5 == 5) # equal to (note: double equals)
print(5 != 3) # not equal to

# you can compare variables too
a = 10
b = 7
print(a > b)
print (b >= a)
x = int(input("Enter a number: "))
